static const char *exdefs_TranslateString(const char *string)
{
  int i;

  if (!string)
    return string;

  // look for matching string
  if (string[0] == '$')
    for (i = 0; i < arrlen(exdefs_strings); ++i)
      if (!stricmp(string + 1, exdefs_strings[i].key))
        return exdefs_strings[i].value;

  return string;
}

