int dsda_ActorNameToType(const char* name) {
  int i;
  const char* const* actor_names = raven ? hexen ? actor_names_hexen :
                                                   actor_names_heretic :
                                                   actor_names_doom;
  int actor_offset = raven ? hexen ? HEXEN_MT_ZERO :
                                     HERETIC_MT_ZERO :
                                     DOOM_MT_ZERO;

  for (i = 0; actor_names[i]; ++i)
    if (!stricmp(name, actor_names[i]))
      return hexen ? actor_offset + i : // Hexen doesn't use dehacked
                     dsda_GetDehMobjIndex(actor_offset + i);

  return NAME_NOT_FOUND;
}

int dsda_ActionNameToNumber(const char* name) {
  int i;

  for (i = 0; action_names[i]; ++i)
    if (action_names[i][0] && !stricmp(name, action_names[i]))
      return i;

  if (!stricmp(name, "Map_SetColormap"))
    return 2701;

  if (!stricmp(name, "Sector_SetColormap"))
    return 2702;

  if (!stricmp(name, "Music_ChangeSong"))
    return 2703;

  if (!stricmp(name, "Music_Stop"))
    return 2704;

  return NAME_NOT_FOUND;
}
